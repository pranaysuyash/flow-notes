"""
Export Manager for FlowNotes
Supports multiple export formats: PDF, HTML, Anki, Obsidian
"""

import os
import re
from pathlib import Path
from typing import List, Dict, Optional
from datetime import datetime
import json

from utils.logger import get_logger

logger = get_logger(__name__)


class ExportManager:
    """Handles exporting notes to various formats"""

    def __init__(self, notes_dir: Path):
        """
        Initialize export manager

        Args:
            notes_dir: Base directory containing notes
        """
        self.notes_dir = Path(notes_dir)
        self.exports_dir = self.notes_dir / "exports"
        self.exports_dir.mkdir(exist_ok=True)

    def export_to_pdf(
        self,
        markdown_content: str,
        output_path: Optional[Path] = None,
        title: str = "FlowNotes Export",
        include_toc: bool = True
    ) -> Path:
        """
        Export markdown to PDF with styling

        Args:
            markdown_content: Markdown text to convert
            output_path: Optional custom output path
            title: Document title
            include_toc: Include table of contents

        Returns:
            Path to generated PDF file
        """
        try:
            import markdown2
            from weasyprint import HTML, CSS
            from weasyprint.text.fonts import FontConfiguration
        except ImportError as e:
            logger.error(f"PDF export requires weasyprint: {e}")
            raise ImportError("Install weasyprint: pip install weasyprint")

        logger.info(f"Generating PDF: {title}")

        # Convert markdown to HTML
        html_content = markdown2.markdown(
            markdown_content,
            extras=[
                "fenced-code-blocks",
                "tables",
                "header-ids",
                "toc" if include_toc else None,
                "code-friendly",
                "footnotes"
            ]
        )

        # Create styled HTML document
        full_html = self._create_pdf_html(html_content, title, include_toc)

        # Generate PDF
        if not output_path:
            timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
            output_path = self.exports_dir / f"{title.replace(' ', '_')}_{timestamp}.pdf"

        font_config = FontConfiguration()
        html_doc = HTML(string=full_html)
        css = CSS(string=self._get_pdf_css(), font_config=font_config)

        html_doc.write_pdf(output_path, stylesheets=[css], font_config=font_config)

        logger.info(f"PDF created: {output_path}")
        return output_path

    def _create_pdf_html(self, content: str, title: str, include_toc: bool) -> str:
        """Create full HTML document for PDF export"""
        toc_section = """
        <div class="toc">
            <h2>Table of Contents</h2>
            {{ toc }}
        </div>
        """ if include_toc else ""

        return f"""
        <!DOCTYPE html>
        <html>
        <head>
            <meta charset="UTF-8">
            <title>{title}</title>
        </head>
        <body>
            <div class="cover">
                <h1>{title}</h1>
                <p class="subtitle">Generated by FlowNotes</p>
                <p class="date">{datetime.now().strftime("%B %d, %Y")}</p>
            </div>
            {toc_section}
            <div class="content">
                {content}
            </div>
            <div class="footer">
                <p>Created with FlowNotes - AI-Powered Learning</p>
            </div>
        </body>
        </html>
        """

