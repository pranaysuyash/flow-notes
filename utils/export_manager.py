    def export_to_html(
        self,
        markdown_content: str,
        output_path: Optional[Path] = None,
        title: str = "FlowNotes Export",
        standalone: bool = True
    ) -> Path:
        """
        Export markdown to styled HTML

        Args:
            markdown_content: Markdown text to convert
            output_path: Optional custom output path
            title: Document title
            standalone: Create standalone HTML file with CSS

        Returns:
            Path to generated HTML file
        """
        try:
            import markdown2
        except ImportError:
            logger.error("HTML export requires markdown2")
            raise ImportError("Install markdown2: pip install markdown2")

        logger.info(f"Generating HTML: {title}")

        # Convert markdown
        html_content = markdown2.markdown(
            markdown_content,
            extras=["fenced-code-blocks", "tables", "header-ids", "code-friendly"]
        )

        if standalone:
            html_content = self._create_standalone_html(html_content, title)

        # Save file
        if not output_path:
            timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
            output_path = self.exports_dir / f"{title.replace(' ', '_')}_{timestamp}.html"

        output_path.write_text(html_content, encoding='utf-8')

        logger.info(f"HTML created: {output_path}")
        return output_path

